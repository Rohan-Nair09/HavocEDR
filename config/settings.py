import logging
from sqlalchemy.exc import IntegrityError
from database.connection import SessionLocal
from database.models import Setting

logger = logging.getLogger(__name__)

class SettingsManager:
    """
    Manages application settings, loading from the SQLite database.
    Provides fallback defaults if settings don't exist.
    """
    _defaults = {
        # Conservative polling intervals keep the endpoint agent responsive
        # without repeatedly sweeping the whole machine every couple seconds.
        "process_monitor_interval": "15.0",
        "service_monitor_interval": "10.0",
        "network_monitor_interval": "10.0",
        "registry_monitor_interval": "10.0",
        "fim_monitor_interval": "10.0",
        "usb_monitor_interval": "10.0",
        "sysmon_monitor_interval": "15.0",
        "ml_detection_enabled": "true",
        "behavior_detection_enabled": "true",
        "correlation_enabled": "true",
        "ai_model": "qwen3:4b",
        "ai_model_base_url": "http://127.0.0.1:11434",
        "response_mode": "Monitor Only",
        "response_terminate_process": "false",
        "response_auto_usb_termination": "false",
        "response_quarantine_file": "false",
        "response_block_network": "false",
    }

    _previous_auto_defaults = {
        "process_monitor_interval": ("5.0", "2.0"),
        "network_monitor_interval": ("5.0", "2.0"),
        "registry_monitor_interval": ("5.0", "2.0"),
        "fim_monitor_interval": "5.0",
        "usb_monitor_interval": "5.0",
        "service_monitor_interval": "5.0",
    }

    @classmethod
    def get(cls, key: str) -> str:
        """Retrieves a setting by key. Creates it with default if missing."""
        db = SessionLocal()
        try:
            setting = db.query(Setting).filter(Setting.key == key).first()
            if setting:
                # Upgrade only values that were generated by an older release;
                # preserve values that the user explicitly configured.
                previous_default = cls._previous_auto_defaults.get(key)
                if (
                    previous_default is not None
                    and setting.value in (previous_default if isinstance(previous_default, tuple) else (previous_default,))
                    and setting.description == f"Auto-generated default for {key}"
                ):
                    setting.value = cls._defaults[key]
                    db.commit()
                return setting.value
            
            # Not found, create default
            default_val = cls._defaults.get(key, "")
            new_setting = Setting(key=key, value=default_val, description=f"Auto-generated default for {key}")
            db.add(new_setting)
            db.commit()
            return default_val
        except IntegrityError as e:
            # Concurrent monitor threads can request the same missing setting
            # during startup. The first insert wins; read that committed row.
            db.rollback()
            try:
                setting = db.query(Setting).filter(Setting.key == key).first()
                if setting is not None:
                    return setting.value
            except Exception:
                db.rollback()
            logger.error("Error fetching setting %s after concurrent insert: %s", key, e)
            return cls._defaults.get(key, "")
        except Exception as e:
            logger.error(f"Error fetching setting {key}: {e}")
            return cls._defaults.get(key, "")
        finally:
            db.close()

    @classmethod
    def get_float(cls, key: str, default: float | None = None) -> float:
        try:
            value = cls.get(key)
            if value:
                return float(value)
        except (TypeError, ValueError):
            pass
        if default is not None:
            return float(default)
        return float(cls._defaults.get(key, 2.0))

    @classmethod
    def set(cls, key: str, value, description: str = "") -> bool:
        """Persist a setting and return whether the database commit succeeded."""
        db = SessionLocal()
        try:
            setting = db.query(Setting).filter(Setting.key == key).first()
            if setting is None:
                setting = Setting(key=key, value=str(value), description=description or key)
                db.add(setting)
            else:
                setting.value = str(value)
                if description:
                    setting.description = description
            db.commit()
            return True
        except Exception as exc:
            logger.error("Error saving setting %s: %s", key, exc)
            db.rollback()
            return False
        finally:
            db.close()
